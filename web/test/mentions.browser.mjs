import { createConsole, cliRunner } from '../server.mjs';
import { fileURLToPath } from 'node:url';
import { mkdtemp, rm } from 'node:fs/promises';
import { spawn } from 'node:child_process';
import assert from 'node:assert/strict';
const home = await mkdtemp('/tmp/agt-resource-browser-');
const profile = await mkdtemp('/tmp/agt-resource-chrome-');
const run = cliRunner(fileURLToPath(new URL('../../target/debug/agt', import.meta.url)), home);
let server, chrome, socket;
try {
  await run(['init', home]);
  await run(['im', 'principal', 'create', 'operator']);
  ({ server } = createConsole({ run, home, principal: 'operator', token: 'browser-test-token' }));
  await new Promise(ok => server.listen(0, '127.0.0.1', ok));
  const url = `http://127.0.0.1:${server.address().port}`;
  chrome = spawn(process.env.CHROME_BINARY || '/opt/google/chrome/chrome', ['--headless=new', '--accept-lang=zh-CN', '--no-sandbox', '--disable-dev-shm-usage', '--remote-debugging-port=0', `--user-data-dir=${profile}`, 'about:blank'], { stdio: ['ignore', 'ignore', 'pipe'] });
  const endpoint = await new Promise((ok, fail) => { let log = ''; chrome.stderr.on('data', chunk => { log += chunk; const match = log.match(/DevTools listening on (ws:\/\/\S+)/); if (match) ok(match[1]); }); chrome.on('error', fail); });
  socket = new WebSocket(endpoint);
  await new Promise(ok => socket.addEventListener('open', ok, { once: true }));
  let sequence = 0; const pending = new Map(); const errors = [];
  socket.addEventListener('message', event => { const value = JSON.parse(event.data); if (value.id) { const p = pending.get(value.id); pending.delete(value.id); value.error ? p.reject(value.error) : p.resolve(value.result); } else if (value.method === 'Runtime.exceptionThrown') errors.push(value.params.exceptionDetails.text); });
  const command = (method, params = {}, sessionId) => new Promise((resolve, reject) => { const id = ++sequence; pending.set(id, { resolve, reject }); socket.send(JSON.stringify({ id, method, params, sessionId })); });
  const { targetId } = await command('Target.createTarget', { url: 'about:blank' });
  const { sessionId } = await command('Target.attachToTarget', { targetId, flatten: true });
  const cdp = (method, params) => command(method, params, sessionId);
  await cdp('Runtime.enable');
  await cdp('Page.enable');
  await cdp('Emulation.setDeviceMetricsOverride', { width: 1280, height: 900, deviceScaleFactor: 1, mobile: false });
  await cdp('Page.navigate', { url: `${url}/#browser-test-token` });
  const evaluate = async expression => { const value = await cdp('Runtime.evaluate', { expression, awaitPromise: true, returnByValue: true }); if (value.exceptionDetails) throw new Error(JSON.stringify(value.exceptionDetails)); return value.result.value; };
  const wait = async expression => { for (let i = 0; i < 150; i++) { if (await evaluate(expression)) return; await new Promise(ok => setTimeout(ok, 100)); } throw new Error(`Timed out: ${expression}`); };
  const click = selector => evaluate(`document.querySelector(${JSON.stringify(selector)}).click()`);
  await wait('document.querySelector("#connection")?.textContent === "本地已连接"');

  await evaluate('renderMessages()');
  assert.match(await evaluate('document.querySelector("#messages .welcome h2").textContent'), /好，/);
  assert.equal(await evaluate('!!document.querySelector("#messages [data-empty-new-chat]")'), true);
  await evaluate(`
    state.polling = true;
    state.conversation = {id: 'sample', state: 'active'};
    state.members = ['operator', 'lead', 'developer', 'role:with space', 'all'].map(principal_id => ({principal_id, left_message_seq: null}));
    state.boot.principals.push({id: 'lead', name: '技术负责人'}, {id: 'developer', name: '开发'}, {id: 'role:with space', name: '特殊身份'}, {id: 'all', name: '同名成员'});
    setupReadOnly(); renderMentions();
  `);
  const type = value => evaluate(`{ const input = document.querySelector('#message-body'); input.focus(); input.value = ${JSON.stringify(value)}; input.setSelectionRange(input.value.length,input.value.length); input.dispatchEvent(new Event('input')); }`);
  const key = key => evaluate(`document.querySelector('#message-body').dispatchEvent(new KeyboardEvent('keydown', {key: ${JSON.stringify(key)}, bubbles: true, cancelable: true}));`);
  await type('@');
  assert.equal(await evaluate('document.querySelectorAll("#mention-menu button").length'), 5);
  await key('ArrowDown'); await key('Enter');
  assert.equal(await evaluate('document.querySelector("#message-body").value'), '@lead ');
  assert.deepEqual(await evaluate('mentionedPrincipals(document.querySelector("#message-body").value)'), ['lead']);
  await type('@开发'); await key('Tab');
  assert.equal(await evaluate('document.querySelector("#message-body").value'), '@developer ');
  await type('/st');
  assert.deepEqual(await evaluate('[...document.querySelectorAll("#mention-menu strong")].map(e => e.textContent.split(" ")[0])'), ['/status', '/stop']);
  await key('Escape');
  assert.equal(await evaluate('document.querySelector("#mention-menu").classList.contains("hidden")'), true);
  await type('/zz');
  assert.equal(await evaluate('document.querySelector("#mention-menu").classList.contains("hidden")'), true);
  await type('hello /st');
  assert.equal(await evaluate('document.querySelector("#mention-menu").classList.contains("hidden")'), true);
  await type('@特殊'); await click('#mention-option-0');
  assert.deepEqual(await evaluate('mentionedPrincipals(document.querySelector("#message-body").value)'), ['role:with space']);
  await type('@同名'); await key('Enter');
  assert.deepEqual(await evaluate('mentionedPrincipals(document.querySelector("#message-body").value)'), ['all']);
  assert.deepEqual(await evaluate('mentionedPrincipals("@lead，看看这个。 @lead @developer")'), ['lead', 'developer']);
  assert.deepEqual(await evaluate('mentionedPrincipals("mail@lead @lead-other @unknown")'), []);
  assert.deepEqual(await evaluate('mentionedPrincipals("@all 请大家回应")'), ['lead', 'developer', 'role:with space', 'all']);
  await type('@'); await key('Escape');
  assert.equal(await evaluate('document.querySelector("#mention-menu").classList.contains("hidden")'), true);
  await type('普通消息');
  assert.deepEqual(await evaluate('mentionedPrincipals(document.querySelector("#message-body").value)'), []);
  await evaluate(`
    window.sent = null;
    api = async (path, data) => { if (path === 'tool') window.sent = data; return {}; };
    messages = conversations = activity = async () => {};
  `);
  await type('@all 请大家看一下'); await click('#send');
  await wait('window.sent !== null && !state.sending');
  assert.deepEqual(await evaluate('window.sent.args.mentions'), ['lead', 'developer', 'role:with space', 'all']);
  assert.equal(await evaluate('window.sent.args.body'), '@all 请大家看一下');
  assert.equal(await evaluate('document.querySelector("#message-body").value'), '');
  await type('@');
  await cdp('Emulation.setDeviceMetricsOverride', {width: 360, height: 844, deviceScaleFactor: 1, mobile: true});
  assert.equal(await evaluate('document.documentElement.scrollWidth <= innerWidth'), true);
  assert.deepEqual(errors, []);
  console.log('Mentions browser passed: search, keyboard/click, all expansion, exact/deduplicated IDs, unusual IDs, removal, send payload, mobile.');
} finally {
  socket?.close(); chrome?.kill('SIGTERM'); run.close(); server?.closeAllConnections(); server?.close();
  await new Promise(ok => setTimeout(ok, 500));
  await rm(home, { recursive: true, force: true }); await rm(profile, { recursive: true, force: true });
}